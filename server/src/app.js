import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import authRoutes from './routes/authRoutes.js';
import rateLimit from 'express-rate-limit';
import financeRoutes from './routes/financeRoutes.js';
import analyticsRoutes from './routes/analyticsRoutes.js';
import calendarRoutes from './routes/calendarRoutes.js';
import intelligenceRoutes from './routes/intelligenceRoutes.js';
import insightRoutes from './routes/insightRoutes.js';
import recommendationRoutes from './routes/recommendationRoutes.js';
import subscriptionRoutes from './routes/subscriptionRoutes.js';
import importRoutes from './routes/importRoutes.js';
import reportRoutes from './routes/reportRoutes.js';
import exportRoutes from './routes/exportRoutes.js';
import bankRoutes from './routes/bankRoutes.js';

export const app = express();
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_URL || 'http://localhost:5173' }));
app.use(express.json({ limit: '100kb' }));
app.use(cookieParser());
app.use('/api/auth', rateLimit({ windowMs: 15 * 60 * 1000, limit: 50, standardHeaders: 'draft-7', legacyHeaders: false }));
app.get('/api/health', (_req, res) => res.json({ status: 'ok', service: 'spendsense-api' }));
app.use('/api/auth', authRoutes);
app.use('/api', financeRoutes);
app.use('/api', analyticsRoutes);
app.use('/api', calendarRoutes);
app.use('/api', intelligenceRoutes);
app.use('/api', insightRoutes);
app.use('/api', recommendationRoutes);
app.use('/api', subscriptionRoutes);
app.use('/api', importRoutes);
app.use('/api', reportRoutes);
app.use('/api', exportRoutes);
app.use('/api', bankRoutes);
app.use((error, _req, res, _next) => {
  console.error(error.message);
  return res.status(500).json({ error: 'The server could not complete that request.' });
});
app.use((_req, res) => res.status(404).json({ error: 'Route not found' }));
